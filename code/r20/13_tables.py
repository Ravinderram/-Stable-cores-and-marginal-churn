M1 = pd.read_csv(R + 'M1_reconciliation.csv'); F1 = pd.read_csv(R + 'F1_ceiling_states.csv')
H = pd.read_csv(R + 'H1_heaping_state.csv', index_col=0)
nceil = int(F1[F1.ceiling_state == True].shape[0])
