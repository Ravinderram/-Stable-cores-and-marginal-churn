    r = T3.loc[k]
    out.append(f"{names[k]} & {f0(r.prevalence)} & {f0(r.P11)} ({r.CI_station.replace('0.', '.').replace('-.', '-.')}) & {r.CI_state} & {f0(r.P01)} & {f0(r.N1)} & {f0(r.N1s)} & {f0(r.N2)} & {pc(r.share_beyond_state)} & {f0(r.jaccard1_mean)} & {icc[k]} & {pc(r.persistent)} \\\\")
