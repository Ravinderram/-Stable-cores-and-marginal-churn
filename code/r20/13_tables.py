# Table 3 persistence
icc = {'FC': '$>$ 0.9', 'BOD': f0(R3.loc['ADV_BOD', 'ICC_M1']), 'DO': f0(R3.loc['ADV_DO', 'ICC_M1']), 'pH': f0(R3.loc['ADV_PH', 'ICC_M1']), '>=2 of 4': '--'}
