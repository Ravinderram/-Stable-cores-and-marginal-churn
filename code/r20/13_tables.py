for ind in ['BOD', 'FC (censored)', 'pH']:
    lo, mn, hi = e(ind, 'low'), e(ind, 'main'), e(ind, 'high')
    cells.append((f"{int(mn.observed_changes):,}", f"{mn.expected_changes_error_only:,.0f} ({lo.expected_changes_error_only:,.0f}-{hi.expected_changes_error_only:,.0f})",
                  f"{100 * mn.repeat_measurement_changes_station_years:.1f}\\% ({100 * lo.repeat_measurement_changes_station_years:.1f}-{100 * hi.repeat_measurement_changes_station_years:.1f})"))
